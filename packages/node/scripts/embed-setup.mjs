// Writes src/server/setup-html.generated.ts (gitignored) exporting the setup page as a string.
// Uses the built page from setup-ui/dist when it exists, otherwise a small stub, so typecheck
// and tests never hit a missing import. `npm run build` at the repo root builds the real page.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const built = new URL('../../../setup-ui/dist/index.html', import.meta.url);
const out = new URL('../src/server/setup-html.generated.ts', import.meta.url);

const html = existsSync(built)
  ? readFileSync(built, 'utf8')
  : '<!doctype html><meta charset="utf-8"><title>goto-sms</title>' +
    '<p>goto-sms v{version}: the setup page was not built. Run <code>npm run build</code>.</p>';

// JSON.stringify keeps backticks and ${ in the page from breaking the module.
const source =
  '// Generated by scripts/embed-setup.mjs. Do not edit; not committed.\n' +
  `export const SETUP_HTML = ${JSON.stringify(html)};\n`;

// Only rewrite on change, so watchers and tsc incremental state aren't disturbed.
if (!existsSync(out) || readFileSync(out, 'utf8') !== source) writeFileSync(out, source);
